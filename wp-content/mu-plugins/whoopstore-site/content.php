<?php
/**
 * Что разрешено сохранять в содержимом страниц и паттернов.
 *
 * WordPress пропускает содержимое через kses у всех, кроме пользователей с
 * правом unfiltered_html (это администраторы). У роли «Менеджер магазина» —
 * той, под которой работает заказчик, — такого права нет, и при любом
 * сохранении из редактора kses вырезал теги <picture> и <source>. А на них
 * держатся мобильные версии картинок в паттернах «Частые вопросы» (на четырёх
 * страницах) и «Промо: ремешки»: заказчик правил бы текст, а на телефоне
 * ломалась бы картинка (найдено 2026-09-18, закрыто 2026-09-22).
 *
 * Поэтому <picture> и <source> добавлены в список разрешённых. Оба тега
 * ничего не выполняют: это выбор файла по ширине экрана, их адреса kses
 * проверяет так же, как у <img>.
 *
 * Почему mu-plugin, а не тема: разметка с <picture> лежит в базе (паттерны и
 * страницы), и при смене или доработке темы она никуда не денется — а вместе
 * с ней должно остаться и разрешение.
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

add_filter( 'wp_kses_allowed_html', function ( $tags, $context ) {
	if ( 'post' !== $context ) {
		return $tags;
	}

	$tags['picture'] = [
		'class' => true,
		'style' => true,
	];

	$tags['source'] = [
		'class'  => true,
		'src'    => true,
		'srcset' => true,
		'sizes'  => true,
		'media'  => true,
		'type'   => true,
		'width'  => true,
		'height' => true,
	];

	return $tags;
}, 10, 2 );
