<?php
/**
 * Обратный адрес писем сайта (envelope sender, он же Return-Path).
 *
 * Без него письмо зависит от того, откуда запущен PHP. У сайта обратный адрес
 * задан в настройках PHP хостинга (webmaster@ домена), и такого ящика нет:
 * уведомление о недоставке теряется. У системного cron настройки другие,
 * обратным адресом становится технический адрес хостинга, и такие письма не
 * доходят как минимум до Gmail (проверено 2026-10-30). Один адрес на все
 * письма убирает зависимость от способа запуска и от хостинга.
 *
 * Адрес — тот же, что менеджер видит в «WooCommerce → Настройки → Письма»
 * как адрес отправителя. У него должен быть настоящий ящик на домене, иначе
 * об ошибках доставки снова никто не узнает.
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

add_action( 'phpmailer_init', function ( $phpmailer ) {
	$address = sanitize_email( (string) get_option( 'woocommerce_email_from_address' ) );

	if ( '' !== $address ) {
		$phpmailer->Sender = $address;
	}
} );
